#!/usr/bin/env node
// Generates figma-plugin/code.js: header + the shared importer (src/figma/importer.js)
// + the plugin's UI wiring. Never hand-edit code.js; edit the importer or this
// script and rerun `npm run build:figma-plugin`.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const importerPath = new URL('../src/figma/importer.js', import.meta.url);
const outPath = new URL('../figma-plugin/code.js', import.meta.url);

const HEADER = `// GENERATED by scripts/build-figma-plugin.mjs from src/figma/importer.js. Do not edit by hand.
//
// designlang Figma plugin — imports a \`*-figma-variables.json\` payload
// (produced by \`designlang <url>\`) into Figma: variables (with aliases, scopes and
// code syntax), text styles, effect styles and, optionally, a Button component.
//
// Accepted payload shapes (unknown keys are ignored):
//   v2 / formatter output (src/formatters/figma.js):
//     { version: 2, collections: [{ name, modes: ["light", "dark"], variables: [{ name, type, values: { light, dark } }] }],
//       textStyles: [...], effectStyles: [...], components: [...] }
//   v1 per-mode:
//     { collections: [{ name, modes: [{ name, variables: [{ name, type, value }] }] }] }
`;

const WIRING = `
figma.showUI(__html__, { width: 420, height: 480, themeColors: true });

figma.ui.onmessage = async (msg) => {
  if (msg.type === "cancel") {
    figma.closePlugin();
    return;
  }
  if (msg.type !== "import") return;

  try {
    const r = await importDesignSystem(figma, msg.data, { components: !!msg.components });
    figma.ui.postMessage({
      type: "done",
      variableCount: r.variables,
      collectionCount: r.collections,
      textStyleCount: r.textStyles,
      effectStyleCount: r.effectStyles,
      componentCount: r.components,
      fontFallbacks: r.fontFallbacks,
    });
    figma.notify(\`designlang: imported \${r.variables} variables across \${r.collections} collections.\`);
  } catch (err) {
    figma.ui.postMessage({ type: "error", message: err.message });
  }
};
`;

export function buildPluginCode() {
  const importer = readFileSync(importerPath, 'utf-8').replace(/^export /m, '');
  return `${HEADER}\n${importer.trimEnd()}\n${WIRING}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outPath, buildPluginCode());
  console.log('wrote figma-plugin/code.js');
}
